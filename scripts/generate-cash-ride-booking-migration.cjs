// Generates the cash-ride booking migration (fee hold + driver-acquisition exception) and its
// rollback from the DEPLOYED trigger text in supabase/baseline/deployed_public_schema.sql.
// The replaced trigger differs from the deployed one only by one added condition.
// Usage: node scripts/generate-cash-ride-booking-migration.cjs
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const baseline=fs.readFileSync(path.join(root,'supabase/baseline/deployed_public_schema.sql'),'utf8').replace(/\r\n/g,'\n');
const NAME='20261266100000_cash_ride_booking_fee_hold';

function deployed(signature){
  const start=baseline.indexOf('CREATE FUNCTION public.'+signature);
  if(start<0)throw Error('not in baseline: '+signature);
  const text=baseline.slice(start,baseline.indexOf('\n\n\n',start)).trimEnd();
  if(!/^\$\$;$/m.test(text.split('\n').pop()))throw Error('unexpected end of '+signature);
  return text;
}
function once(text,from,to,label){
  const n=text.split(from).length-1;
  if(n!==1)throw Error(label+': expected exactly 1 match, found '+n);
  return text.replace(from,to);
}
const orReplace=t=>t.replace(/^CREATE FUNCTION/,'CREATE OR REPLACE FUNCTION');
// Deployed payment_status check, widened by exactly two cash states.
const checkLine=baseline.split(String.fromCharCode(10)).find(l=>l.trim().startsWith('CONSTRAINT jobs_payment_status_check CHECK'));
if(!checkLine)throw Error('jobs_payment_status_check not in baseline');
const oldCheck=checkLine.trim().replace(/^CONSTRAINT jobs_payment_status_check /,'').replace(/,$/,'');
const newCheck=once(oldCheck,"'requires_review'::text]","'requires_review'::text, 'cash_due'::text, 'cash_collected'::text]",'payment_status check');
const eligibility=deployed('enforce_job_payment_eligibility()');
const newEligibility=once(eligibility,
  "            'paid', 'wallet_funded', 'authorized', 'requires_capture', 'succeeded', 'captured'\n        ) THEN",
  "            'paid', 'wallet_funded', 'authorized', 'requires_capture', 'succeeded', 'captured'\n        ) AND NOT public.cash_ride_acquirable_v1e(NEW) THEN",'eligibility');

const up=`-- Cash-ride booking, phase 1 (generated by scripts/generate-cash-ride-booking-migration.cjs).
-- A cash Ride is secured by an on-session card HOLD for its fee terms (no-show / late
-- cancellation). The hold lives here, not in jobs.payment_intent_id, because cash-credit 1E
-- requires a cash job to carry no PaymentIntent. A driver may acquire a cash_due job only when
-- it is a cash Ride with full customer cash collection, in an ENABLED cash-ride pilot market,
-- with an authorised hold for that job, customer and currency. Card and wallet jobs are
-- unchanged. This migration enables no market.
BEGIN;

-- Two cash payment states: cash_due (customer pays the driver in cash at the end of the ride;
-- the state cash-credit 1E reserves against) and cash_collected (completed cash ride).
ALTER TABLE public.jobs DROP CONSTRAINT jobs_payment_status_check;
ALTER TABLE public.jobs ADD CONSTRAINT jobs_payment_status_check ${newCheck};

CREATE TABLE public.cash_ride_fee_holds_v1e (
    job_id uuid PRIMARY KEY REFERENCES public.jobs(id),
    tenant_id uuid NOT NULL,
    customer_id uuid NOT NULL,
    provider text NOT NULL CHECK (provider ~ '^[a-z][a-z0-9_-]{1,31}$'),
    merchant_account_ref text NOT NULL CHECK (length(btrim(merchant_account_ref)) BETWEEN 1 AND 100),
    provider_payment_reference text UNIQUE CHECK (provider_payment_reference IS NULL OR length(provider_payment_reference) BETWEEN 3 AND 255),
    amount_minor bigint NOT NULL CHECK (amount_minor > 0),
    currency_code text NOT NULL CHECK (currency_code ~ '^[A-Z]{3}$'),
    fee_terms jsonb NOT NULL,
    status text NOT NULL DEFAULT 'created' CHECK (status IN ('created','authorized','captured','released','failed')),
    captured_minor bigint NOT NULL DEFAULT 0 CHECK (captured_minor >= 0 AND captured_minor <= amount_minor),
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    updated_at timestamp with time zone NOT NULL DEFAULT now(),
    CHECK (status <> 'authorized' OR provider_payment_reference IS NOT NULL),
    CHECK (status = 'captured' OR captured_minor = 0)
);
ALTER TABLE public.cash_ride_fee_holds_v1e ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.cash_ride_fee_holds_v1e FROM PUBLIC;
DO $g$ BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='anon') THEN REVOKE ALL ON TABLE public.cash_ride_fee_holds_v1e FROM anon; END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='authenticated') THEN REVOKE ALL ON TABLE public.cash_ride_fee_holds_v1e FROM authenticated; END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='service_role') THEN
    REVOKE ALL ON TABLE public.cash_ride_fee_holds_v1e FROM service_role;
    GRANT SELECT, INSERT, UPDATE ON TABLE public.cash_ride_fee_holds_v1e TO service_role;
  END IF;
END $g$;

CREATE FUNCTION public.cash_ride_acquirable_v1e(j public.jobs) RETURNS boolean
    LANGUAGE sql STABLE SECURITY DEFINER
    SET search_path TO 'pg_catalog', 'public'
    AS $$
 -- Strictly true/false: a NULL here would make the trigger's NOT ... evaluate to NULL and let
 -- the acquisition through.
 SELECT coalesce((j.payment_method = 'cash'
  AND j.payment_status = 'cash_due'
  AND j.payment_intent_id IS NULL
  AND j.metadata->>'cash_collection_mode' = 'full_customer_charge'
  AND EXISTS (SELECT 1 FROM public.service_types s WHERE s.id = j.service_type_id AND s.slug = 'ride')
  AND coalesce(public.driver_cash_credit_market_enabled_v1e(j.country_code, j.currency_code), false)
  AND EXISTS (SELECT 1 FROM public.cash_ride_fee_holds_v1e h
              WHERE h.job_id = j.id AND h.status = 'authorized' AND h.customer_id = j.customer_id
                AND h.tenant_id = j.tenant_id AND h.currency_code = j.currency_code)), false) $$;
REVOKE ALL ON FUNCTION public.cash_ride_acquirable_v1e(public.jobs) FROM PUBLIC;
DO $g$ BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='anon') THEN REVOKE ALL ON FUNCTION public.cash_ride_acquirable_v1e(public.jobs) FROM anon; END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='authenticated') THEN REVOKE ALL ON FUNCTION public.cash_ride_acquirable_v1e(public.jobs) FROM authenticated; END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='service_role') THEN GRANT EXECUTE ON FUNCTION public.cash_ride_acquirable_v1e(public.jobs) TO service_role; END IF;
END $g$;

${orReplace(newEligibility)}

COMMIT;
`;
const down=`-- Rollback of ${NAME}: restores the deployed enforce_job_payment_eligibility body exactly,
-- then drops the acquisition check and the fee-hold table. Release or capture any authorised
-- holds at the provider BEFORE running this; the table's references are dropped with it.
BEGIN;

${orReplace(eligibility)}

DROP FUNCTION public.cash_ride_acquirable_v1e(public.jobs);
DROP TABLE public.cash_ride_fee_holds_v1e;
-- Fails (and rolls back everything) while any job still has a cash payment state.
ALTER TABLE public.jobs DROP CONSTRAINT jobs_payment_status_check;
ALTER TABLE public.jobs ADD CONSTRAINT jobs_payment_status_check ${oldCheck};

COMMIT;
`;
module.exports={NAME,up,down,oldCheck,newCheck,deployedBodies:{eligibility},newBodies:{eligibility:newEligibility}};
if(require.main===module){
  fs.writeFileSync(path.join(root,'supabase/migrations',NAME+'.sql'),up);
  fs.writeFileSync(path.join(root,'deploy/vaydu-cash-ride-market-pilot',NAME+'.down.sql'),down);
  console.log('written',NAME);
}
