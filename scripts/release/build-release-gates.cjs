#!/usr/bin/env node
// Generate the read-only host gates for the develop release from the rehearsed fingerprint lists:
//   pre-release-fingerprints.tsv   develop's current bodies of the 4 functions the release replaces
//                                  (from the live inventory 20261112T203946Z, EOL-insensitive md5)
//   post-release-fingerprints.tsv  the 15 functions the release creates/replaces, as rehearsed
// Outputs PREREQ.sql (before migrating: develop must be exactly the reconciled state) and VERIFY.sql
// (run by the rollout script before any container change: the release must be applied exactly).
'use strict';
const fs=require('fs'),path=require('path');
const dir=path.resolve(__dirname,'../../deploy/vaydu-develop-release');
const rd=f=>fs.readFileSync(path.join(dir,f),'utf8').split('\n').map(l=>l.replace(/\r$/,'')).filter(Boolean).map(l=>{const i=l.lastIndexOf('\t');return [l.slice(0,i),l.slice(i+1).trim()];});
const pre=rd('pre-release-fingerprints.tsv'),post=rd('post-release-fingerprints.tsv');
for(const [s,m] of [...pre,...post])if(!/^[0-9a-f]{32}$/.test(m))throw new Error(`bad fingerprint for ${s}`);
const replaced=new Set(pre.map(x=>x[0]));const created=post.filter(([s])=>!replaced.has(s)).map(x=>x[0]);
const BS='\\';
const fp="md5(replace(pg_get_functiondef(p.oid),chr(13),''))";
const sig="n.nspname||'.'||p.proname||'('||pg_get_function_identity_arguments(p.oid)||')'";
const lit=s=>"'"+s.replace(/'/g,"''")+"'";
const pairs=rows=>rows.map(([s,m])=>`  (${lit(s)},${lit(m)})`).join(',\n');
const NL=`E'${BS}n`;

const prereq=[
'-- PREREQ for the develop release (read-only). Generated by scripts/release/build-release-gates.cjs.',
'-- Stops (ON_ERROR_STOP) unless develop is exactly the reconciled pre-release state the rehearsal used:',
'-- the 4 functions the release replaces have the recorded bodies, none of the release objects exists,',
'-- and no job uses the cash collection mode.',
`${BS}set ON_ERROR_STOP 1`,
'BEGIN READ ONLY;',
'DO $pre$',
"DECLARE r record; v text; bad text := '';",
'BEGIN',
' FOR r IN SELECT * FROM (VALUES',
pairs(pre)+') t(sig,md5) LOOP',
`  SELECT ${fp} INTO v FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace WHERE ${sig} = r.sig;`,
`  IF v IS DISTINCT FROM r.md5 THEN bad := bad || format(${NL}  replaced function differs from the reconciled state: %s (found %s)', r.sig, coalesce(v,'MISSING')); END IF;`,
' END LOOP;',
' FOR r IN SELECT * FROM (VALUES',
created.map(s=>`  (${lit(s)})`).join(',\n')+') t(sig) LOOP',
`  IF EXISTS (SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace WHERE ${sig} = r.sig) THEN bad := bad || format(${NL}  already exists: %s', r.sig); END IF;`,
' END LOOP;',
` IF to_regclass('public.driver_cash_credit_markets_v1e') IS NOT NULL THEN bad := bad || ${NL}  already exists: driver_cash_credit_markets_v1e'; END IF;`,
` IF to_regclass('public.cash_ride_fee_holds_v1e') IS NOT NULL THEN bad := bad || ${NL}  already exists: cash_ride_fee_holds_v1e'; END IF;`,
` IF EXISTS (SELECT 1 FROM public.jobs WHERE metadata->>'cash_collection_mode'='full_customer_charge') THEN bad := bad || ${NL}  a job already uses cash_collection_mode=full_customer_charge'; END IF;`,
" IF bad <> '' THEN RAISE EXCEPTION 'PREREQ FAILED:%', bad; END IF;",
` RAISE NOTICE 'PREREQ OK: % replaced functions match, % release functions absent, cash tables absent, no cash-mode jobs', ${pre.length}, ${created.length};`,
'END $pre$;',
"SELECT 'payment_status values on jobs' AS check_name, coalesce(string_agg(DISTINCT coalesce(payment_status,'<null>'), ', '),'none') AS found FROM public.jobs;",
'ROLLBACK;',''].join('\n');

const verify=[
'-- VERIFY for the develop release (read-only). Generated by scripts/release/build-release-gates.cjs.',
'-- Run by rollout-develop-52097ef.sh before it builds or recreates any container, and after deployment.',
'-- Stops (ON_ERROR_STOP) unless the release migration is applied exactly (15 functions equal the',
'-- rehearsed bodies, EOL-insensitive) and no cash-ride market is enabled.',
`${BS}set ON_ERROR_STOP 1`,
'BEGIN READ ONLY;',
'DO $verify$',
"DECLARE r record; v text; bad text := '';",
'BEGIN',
' FOR r IN SELECT * FROM (VALUES',
pairs(post)+') t(sig,md5) LOOP',
`  SELECT ${fp} INTO v FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace WHERE ${sig} = r.sig;`,
`  IF v IS DISTINCT FROM r.md5 THEN bad := bad || format(${NL}  %s: expected %s, found %s', r.sig, r.md5, coalesce(v,'MISSING')); END IF;`,
' END LOOP;',
` IF to_regclass('public.driver_cash_credit_markets_v1e') IS NULL OR to_regclass('public.cash_ride_fee_holds_v1e') IS NULL THEN bad := bad || ${NL}  cash release tables missing'; END IF;`,
" IF bad <> '' THEN RAISE EXCEPTION 'VERIFY FAILED (release migration not applied exactly):%', bad; END IF;",
" IF EXISTS (SELECT 1 FROM public.driver_cash_credit_markets_v1e WHERE enabled) THEN RAISE EXCEPTION 'VERIFY FAILED: a cash-ride market is enabled'; END IF;",
` RAISE NOTICE 'VERIFY OK: release schema present (% functions), no cash-ride market enabled', ${post.length};`,
'END $verify$;',
'-- Objects the top-up flow calls (unchanged by this release).',
"SELECT 'public.confirm_wallet_topup_with_total(uuid,text,text,text,bigint,text)'::regprocedure AS confirm_fn,",
"       'public.mark_wallet_topup_failed(uuid,text)'::regprocedure AS mark_failed_fn,",
"       'public.record_driver_topup_provider_observation(uuid,jsonb)'::regprocedure AS observe_fn,",
"       'public.record_wallet_topup_provider_reference(uuid,text)'::regprocedure AS bind_ref_fn;",
'SELECT count(*) AS enabled_cash_markets FROM public.driver_cash_credit_markets_v1e WHERE enabled;',
'SELECT count(*) AS enabled_cancellation_policies FROM public.cancellation_policies WHERE enabled;',
'ROLLBACK;',''].join('\n');

fs.writeFileSync(path.join(dir,'PREREQ.sql'),prereq);
fs.writeFileSync(path.join(dir,'VERIFY.sql'),verify);
console.log(`PREREQ.sql: ${pre.length} replaced, ${created.length} created; VERIFY.sql: ${post.length} functions`);
