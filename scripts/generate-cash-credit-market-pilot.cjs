// Generates the market-scoped cash-ride pilot migration and its rollback from the DEPLOYED
// function text in supabase/baseline/deployed_public_schema.sql. Each replaced function differs
// from the deployed one only in the global pilot check; every substitution must match exactly
// once or generation fails. Usage: node scripts/generate-cash-credit-market-pilot.cjs
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const baseline=fs.readFileSync(path.join(root,'supabase/baseline/deployed_public_schema.sql'),'utf8').replace(/\r\n/g,'\n');
const NAME='20261266000000_driver_cash_credit_market_pilot';

function deployed(signature){
  const start=baseline.indexOf('CREATE FUNCTION public.'+signature);
  if(start<0)throw Error('not in baseline: '+signature);
  const end=baseline.indexOf('\n\n\n',start);
  const text=baseline.slice(start,end).trimEnd();
  if(!/END \$[_a-z]*\$;$/.test(text))throw Error('unexpected end of '+signature);
  return text;
}
function once(text,from,to,label){
  const n=text.split(from).length-1;
  if(n!==1)throw Error(label+': expected exactly 1 match, found '+n);
  return text.replace(from,to);
}
const orReplace=t=>t.replace(/^CREATE FUNCTION/,'CREATE OR REPLACE FUNCTION');

const status=deployed('driver_cash_credit_status_v1f(p_driver_id uuid)');
const trigger=deployed('enforce_ride_cash_credit_v1e()');
const reserve=deployed('reserve_cash_job_credit_v1e(p_job_id uuid, p_driver_id uuid)');

const newStatus=once(status,
  "'pilotEnabled',public.driver_cash_credit_enabled_v1e(),",
  "'pilotEnabled',public.driver_cash_credit_market_enabled_v1e(v_country,v_currency),",'status');
const newTrigger=once(trigger,
  " IF NOT public.driver_cash_credit_enabled_v1e() OR NEW.payment_method IS DISTINCT FROM 'cash' THEN RETURN NEW; END IF;",
  " IF NEW.payment_method IS DISTINCT FROM 'cash' OR NOT public.driver_cash_credit_market_enabled_v1e(NEW.country_code,NEW.currency_code) THEN RETURN NEW; END IF;",'trigger');
let newReserve=once(reserve,
  " IF NOT public.driver_cash_credit_enabled_v1e() THEN RAISE EXCEPTION 'Cash credit pilot disabled' USING ERRCODE='CE001'; END IF;\n SELECT * INTO STRICT j FROM public.jobs WHERE id=p_job_id FOR UPDATE;\n",
  " SELECT * INTO STRICT j FROM public.jobs WHERE id=p_job_id FOR UPDATE;\n IF NOT public.driver_cash_credit_market_enabled_v1e(j.country_code,j.currency_code) THEN RAISE EXCEPTION 'Cash credit pilot disabled for this market' USING ERRCODE='CE001'; END IF;\n",'reserve');

const header=`-- Market-scoped cash-ride pilot (generated by scripts/generate-cash-credit-market-pilot.cjs).
-- Before: one GLOBAL switch (driver_cash_credit_config_v1e.ride_cash_credit) turned cash-ride credit
-- enforcement on for every market at once. After: enforcement applies to a country/currency only
-- when the global switch is on AND that market has an enabled row here AND the currency matches
-- market_availability. The global switch remains the kill switch. Markets without a row keep the
-- existing (non-pilot) behaviour. This migration enables NO market. Privileges mirror the global switch:
-- the table is written only by the database owner; the check is executable by service_role only.
-- Replaced functions are the deployed bodies with only the pilot check changed.
`;
const up=`${header}BEGIN;

CREATE TABLE public.driver_cash_credit_markets_v1e (
    country_code text NOT NULL CHECK (country_code ~ '^[A-Z]{2}$'),
    currency_code text NOT NULL CHECK (currency_code ~ '^[A-Z]{3}$'),
    enabled boolean NOT NULL DEFAULT false,
    note text CHECK (note IS NULL OR length(note) <= 200),
    updated_at timestamp with time zone NOT NULL DEFAULT now(),
    PRIMARY KEY (country_code, currency_code)
);
ALTER TABLE public.driver_cash_credit_markets_v1e ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.driver_cash_credit_markets_v1e FROM PUBLIC;
DO $g$ BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='anon') THEN REVOKE ALL ON TABLE public.driver_cash_credit_markets_v1e FROM anon; END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='authenticated') THEN REVOKE ALL ON TABLE public.driver_cash_credit_markets_v1e FROM authenticated; END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='service_role') THEN REVOKE ALL ON TABLE public.driver_cash_credit_markets_v1e FROM service_role; END IF;
END $g$;

CREATE FUNCTION public.driver_cash_credit_market_enabled_v1e(p_country text, p_currency text) RETURNS boolean
    LANGUAGE sql STABLE SECURITY DEFINER
    SET search_path TO 'pg_catalog', 'public'
    AS $$
 SELECT public.driver_cash_credit_enabled_v1e()
  AND EXISTS (SELECT 1 FROM public.driver_cash_credit_markets_v1e m
              WHERE m.country_code=upper(p_country) AND m.currency_code=upper(p_currency) AND m.enabled)
  AND EXISTS (SELECT 1 FROM public.market_availability a
              WHERE a.country_code=upper(p_country) AND upper(a.supported_currency)=upper(p_currency)) $$;
REVOKE ALL ON FUNCTION public.driver_cash_credit_market_enabled_v1e(text, text) FROM PUBLIC;
DO $g$ BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='anon') THEN REVOKE ALL ON FUNCTION public.driver_cash_credit_market_enabled_v1e(text, text) FROM anon; END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='authenticated') THEN REVOKE ALL ON FUNCTION public.driver_cash_credit_market_enabled_v1e(text, text) FROM authenticated; END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='service_role') THEN GRANT EXECUTE ON FUNCTION public.driver_cash_credit_market_enabled_v1e(text, text) TO service_role; END IF;
END $g$;

${orReplace(newStatus)}

${orReplace(newTrigger)}

${orReplace(newReserve)}

COMMIT;
`;
const down=`-- Rollback of ${NAME}: restores the three deployed function bodies exactly, then drops the
-- market table and function. Cash-ride enforcement returns to the single global switch.
BEGIN;

${orReplace(status)}

${orReplace(trigger)}

${orReplace(reserve)}

DROP FUNCTION public.driver_cash_credit_market_enabled_v1e(text, text);
DROP TABLE public.driver_cash_credit_markets_v1e;

COMMIT;
`;
module.exports={NAME,up,down,deployedBodies:{status,trigger,reserve},newBodies:{status:newStatus,trigger:newTrigger,reserve:newReserve}};
if(require.main===module){
  fs.writeFileSync(path.join(root,'supabase/migrations',NAME+'.sql'),up);
  fs.writeFileSync(path.join(root,'deploy/vaydu-cash-ride-market-pilot',NAME+'.down.sql'),down);
  console.log('written',NAME);
}
